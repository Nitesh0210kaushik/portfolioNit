/** Finds the logo for a label such as "Angular 16" or "React.js"; undefined when there is none. */
export function findLogo(label: string): TechLogo | undefined {
  const key = label.toLowerCase().trim();
  return BY_LABEL[key] ?? BY_LABEL[key.replace(/\s+\d+$/, '')];
}
